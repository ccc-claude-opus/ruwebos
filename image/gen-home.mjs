// Generates the home screen home/public/index.html from the apps in image/rucloud.toml:
// each app's public/manifest.webmanifest (name, description, theme_color, icon); apps without a
// manifest (rucloud's examples) use the fallback table below.
//   node image/gen-home.mjs <rucloud checkout>
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, basename } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const rucloud = process.argv[2] || join(root, '../rucloud');
const fallback = {
  myshop: ['MyShop', '個人商店與收銀', '#e8590c', '店'],
  friendbook: ['Friendbook', '貼文、按讚、留言、追蹤', '#1971c2', '友'],
  markpedia: ['Markpedia', 'Markdown 知識庫', '#2f9e44', '典'],
  music: ['琴鍵實驗室', '樂理、彈琴、MIDI', '#9c36b5', '琴'],
  boardgame: ['棋藝軒', '棋類與桌遊對戰', '#c92a2a', '棋'],
  'app-builder': ['App Builder', 'AI 網站產生器（需自備金鑰）', '#5f3dc4', '造'],
  webportal: ['Webportal', '入口網站', '#f08c00', '門'],
  ccc: ['網頁導航', '常用網站連結', '#495057', '航'],
};

// the app paths in the system disk's rucloud.toml: /opt/ruwebos/apps/<x> (ours) and /opt/ruwebos/examples/... (rucloud's)
const toml = readFileSync(join(root, 'image/rucloud.toml'), 'utf8');
const paths = [...toml.matchAll(/^path\s*=\s*"([^"]+)"/gm)].map((m) => m[1]).filter((p) => !p.endsWith('/home'));
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

const ours = [];
const more = [];
for (const p of paths) {
  const local = p.replace('/opt/ruwebos/apps/', join(root, 'apps/')).replace('/opt/ruwebos/examples/', join(rucloud, '/'));
  const name = basename(p);
  const mf = join(local, 'public/manifest.webmanifest');
  if (existsSync(mf)) {
    const m = JSON.parse(readFileSync(mf, 'utf8'));
    const icon = m.icons?.[0]?.src || '';
    ours.push({ name, title: m.short_name || m.name, desc: m.description || '', color: m.theme_color, icon });
  } else {
    const [title, desc, color, glyph] = fallback[name] || [name, '', '#868e96', name[0].toUpperCase()];
    more.push({ name, title, desc, color, glyph });
  }
}

const card = (a) => `    <a class="app" data-app="${esc(a.name)}" href="http://${esc(a.name)}.localhost:8700/">
      ${a.icon
        ? `<img class="icon" src="http://${esc(a.name)}.localhost:8700${esc(a.icon)}" alt="" width="48" height="48">`
        : `<b class="icon" style="background:${esc(a.color)}">${esc(a.glyph)}</b>`}
      <span><strong>${esc(a.title)}</strong><small>${esc(a.desc)}</small></span>
    </a>`;

const html = `<!doctype html>
<html lang="zh-Hant">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>ruwebos</title>
<link rel="stylesheet" href="/home.css">
</head>
<body>
<!-- Generated by image/gen-home.mjs from the apps' manifests; do not edit. -->
<main>
  <header>
    <h1>ru<span>webos</span></h1>
    <p>以瀏覽器為介面的系統：每個應用是一個 rucloud Worker，資料存在資料碟，重開機後還在。</p>
  </header>
  <section class="grid">
${ours.map(card).join('\n')}
  </section>
  <h2>更多應用</h2>
  <section class="grid">
${more.map(card).join('\n')}
  </section>
  <footer>ruvm · Debian 13 · rucloud · rubrowser</footer>
</main>
<script>
  // the apps live on the same edge port as this page
  if (location.port && location.port !== '8700') {
    document.querySelectorAll('a[data-app], img.icon').forEach(function (el) {
      var attr = el.tagName === 'A' ? 'href' : 'src';
      el.setAttribute(attr, el.getAttribute(attr).replace(':8700', ':' + location.port));
    });
  }
</script>
</body>
</html>
`;
writeFileSync(join(root, 'home/public/index.html'), html);
console.log(`   home: ${ours.length} apps + ${more.length} more`);
