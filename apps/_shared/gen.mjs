// Regenerates assets.js from ui.css and enhance.js (run by image/build.sh; commit the result so the apps
// also run straight from the repo with `rucloud dev`).
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('.', import.meta.url);
const read = (f) => readFileSync(new URL(f, dir), 'utf8');
const out = `// Generated by gen.mjs from ui.css and enhance.js; do not edit.
export const assets = {
  '/_ui/ui.css': { type: 'text/css; charset=utf-8', body: ${JSON.stringify(read('ui.css'))} },
  '/_ui/enhance.js': { type: 'text/javascript; charset=utf-8', body: ${JSON.stringify(read('enhance.js'))} },
};
`;
writeFileSync(new URL('assets.js', dir), out);
